# python has a extensive maths built - in function.
# built - in maths function
x = min(5, 10, 25)
y = max(5, 10, 25)
print(x)
print(y)



# abs() - this function returns absolute positive value.
x = abs(-7.25)
print(x)

# pow(x, y)- this function returns the value of x to the power y.
x = pow(2,4)
print(x)

# we can also import maths module externally
import math
x = math.sqrt(36)
print(x)
# math.ceil() and math.floor()
import math
x = math.ceil(1.4) # this will round the number up to the nearest integer
y = math.floor(1.4) # this will round the number down to the nearest integer
print(x)
print(y)
# math.pi
import math
x = math.pi
print(x)

#factorial of a number : math.factorial()
import math
x = math.factorial(5)
print(x)